// ---- Flag rasterization (browser-only; Node falls back to ISO chips) ----------
const flagPngCache = {};

async function rasterizeFlag(code) {
  const svg = rawFlagSvg(code);
  if (!svg || typeof document === 'undefined') return null;
  try {
    // Give the SVG explicit intrinsic dimensions (from its viewBox) so
    // browsers rasterize it at the correct 3:2 aspect ratio.
    const view = svg.match(/viewBox="([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)"/);
    const vw = view ? parseFloat(view[3]) : 640;
    const vh = view ? parseFloat(view[4]) : 480;
    const fixed = svg.replace(/<svg([^>]*)>/, (m, attrs) => {
      const addW = !/\bwidth\s*=/.test(attrs);
      const addH = !/\bheight\s*=/.test(attrs);
      return `<svg${attrs}${addW ? ` width="${vw}"` : ''}${addH ? ` height="${vh}"` : ''}>`;
    });
    const size = 96;
    const canvas = document.createElement('canvas');
    canvas.width = size;
    canvas.height = Math.round((size * vh) / vw);
    const ctx = canvas.getContext('2d');
    const img = new Image();
    const url = URL.createObjectURL(new Blob([fixed], { type: 'image/svg+xml' }));
    await new Promise((resolve, reject) => {
      img.onload = resolve;
      img.onerror = reject;
      img.src = url;
    });
    ctx.drawImage(img, 0, 0, size, canvas.height);
    URL.revokeObjectURL(url);
    // Pre-mask the flag as a rounded rectangle so the PDF needs no doc-level
    // clipping (which could leave an unbalanced graphics state).
    const r = Math.round(size * 0.12);
    const mask = document.createElement('canvas');
    mask.width = size;
    mask.height = canvas.height;
    const mctx = mask.getContext('2d');
    mctx.beginPath();
    mctx.moveTo(r, 0);
    mctx.arcTo(size, 0, size, canvas.height, r);
    mctx.arcTo(size, canvas.height, 0, canvas.height, r);
    mctx.arcTo(0, canvas.height, 0, 0, r);
    mctx.arcTo(0, 0, size, 0, r);
    mctx.closePath();
    mctx.fill();
    mctx.globalCompositeOperation = 'source-in';
    mctx.drawImage(canvas, 0, 0);
    return mask.toDataURL('image/png');
  } catch (e) {
    return null;
  }
}

async function getFlagPng(code) {
  if (!code || code === 'Unknown') return null;
  const key = code.toUpperCase();
  if (key in flagPngCache) return flagPngCache[key];
  const png = await rasterizeFlag(key);
  flagPngCache[key] = png || null;
  return flagPngCache[key];
}

