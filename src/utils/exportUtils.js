function _getFlagEmojiJSPDF(code) {
  if (!code || code === 'Unknown') return '';
  try {
    const c = code.toUpperCase();
    if (c.length === 2) {
      return String.fromCodePoint(...c.split('').map(ch => 0x1F1E6 + ch.charCodeAt(0) - 65));
    }
  } catch (e) {}
  return '';
}

