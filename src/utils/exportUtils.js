      3: { cellWidth: (pageW - 24) * 0.18, halign: 'left' },           // Type: left
      4: { cellWidth: (pageW - 24) * 0.22, halign: 'left' },           // Display Name: left
      5: { cellWidth: (pageW - 24) * 0.12, halign: 'center' },          // Profile: center
