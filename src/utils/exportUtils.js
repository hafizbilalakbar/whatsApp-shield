// ---- Avatar fetching / normalization ----------------------------------------
async function fetchAvatars(records) {
  const list = new Array(records.length).fill(null);
  const concurrency = 6;
  const tasks = records.map((r, idx) => {
    const phoneDigits = String(r.cleanNumber || r.number || '').replace(/\D/g, '');
    const hasAvatar = (r.profilePhotoAvailable === true || !!(r.avatar || r.profileImageUrl)) && r.exists && phoneDigits;
    return {
      idx,
      task: hasAvatar ? fetchImageDataURL(`/api/profile-picture?phone=${phoneDigits}`) : Promise.resolve(null),
    };
  });
  for (let start = 0; start < tasks.length; start += concurrency) {
    const batch = tasks.slice(start, start + concurrency);
    const settled = await Promise.all(batch.map((b) => b.task));
    batch.forEach((b, i) => {
      list[b.idx] = settled[i] || null;
    });
  }
  const out = new Array(records.length).fill(null);
  await Promise.all(
    list.map(async (src, i) => {
      if (!src) return;
      out[i] = await normalizeAvatarDataURL(src);
    }),
  );
  return out;
}

function normalizeAvatarDataURL(dataUrl) {
  return new Promise((resolve) => {
    try {
      const img = new Image();
      img.onload = () => {
        try {
          const size = 22;
          const canvas = document.createElement('canvas');
          canvas.width = size;
          canvas.height = size;
          const ctx = canvas.getContext('2d');
          const srcW = img.naturalWidth || size;
          const srcH = img.naturalHeight || size;
          const scale = Math.max(size / srcW, size / srcH);
          const sw = size / scale;
          const sh = size / scale;
          const sx = (srcW - sw) / 2;
          const sy = (srcH - sh) / 2;
          ctx.drawImage(img, sx, sy, sw, sh, 0, 0, size, size);
          // Pre-mask the avatar as a circle so the PDF needs no doc-level
          // clipping (which could leave an unbalanced graphics state).
          ctx.globalCompositeOperation = 'destination-in';
          ctx.beginPath();
          ctx.arc(size / 2, size / 2, size / 2, 0, Math.PI * 2);
          ctx.fill();
          ctx.globalCompositeOperation = 'source-over';
          resolve(canvas.toDataURL('image/png'));
        } catch (e) {
          resolve(dataUrl);
        }
      };
      img.onerror = () => resolve(null);
      img.src = dataUrl;
    } catch (e) {
      resolve(null);
    }
  });
}

// ---- Data helpers ---------------------------------------------------------------
function formatExportTimestamp(date) {
  return `${date.toLocaleDateString()} ${date.toLocaleTimeString()}`;
}

export function filterKeyFromLabel(label) {
  const l = String(label || '').toLowerCase();
  if (l.startsWith('not registered')) return 'unregistered';
  if (l.startsWith('registered')) return 'registered';
  if (l.startsWith('invalid')) return 'invalid';
  if (l.includes('business')) return 'business';
  if (l.includes('consumer')) return 'consumer';
  return 'all';
}

export function recordStatusKey(rec) {
  if (rec?.exists === true) return 'registered';
  if (rec?.isValidFormat === false) return 'invalid';
  return 'unregistered';
}

export function recordStatus(rec) {
  const key = recordStatusKey(rec);
  return key === 'registered' ? 'Registered' : key === 'invalid' ? 'Invalid Format' : 'Not Registered';
}

export function applyReportFilter(records, filterKey) {
  if (!Array.isArray(records)) return [];
  if (filterKey === 'registered') return records.filter((r) => recordStatusKey(r) === 'registered');
  if (filterKey === 'unregistered') return records.filter((r) => recordStatusKey(r) === 'unregistered');
  if (filterKey === 'invalid') return records.filter((r) => recordStatusKey(r) === 'invalid');
  if (filterKey === 'business') return records.filter((r) => r.isBusiness === true);
  if (filterKey === 'consumer') return records.filter((r) => r.isBusiness !== true);
  return records;
}

export function computeTotals(records) {
  let registered = 0;
  let notRegistered = 0;
  let invalid = 0;
  (records || []).forEach((r) => {
    const key = recordStatusKey(r);
    if (key === 'registered') registered += 1;
    else if (key === 'unregistered') notRegistered += 1;
    else invalid += 1;
  });
  return { total: records.length, registered, notRegistered, invalid };
}

export function countryOfRecord(rec) {
  const iso = String(rec?.detectedCountry || '').trim();
  if (iso && iso !== 'Unknown' && iso !== 'N/A') {
    return { code: iso.toUpperCase(), name: getCountryName(iso), dialCode: getCountryDialCode(iso) };
  }
  const fromNumber = getCountryFromNumber(rec?.formatted || rec?.number || '');
  if (fromNumber && fromNumber.code && fromNumber.code !== 'Unknown') {
    return { code: fromNumber.code, name: fromNumber.name, dialCode: getCountryDialCode(fromNumber.code) };
  }
  return { code: 'Unknown', name: 'Unknown', dialCode: null };
}

export function buildCountryGroups(records) {
  const map = new Map();
  (records || []).forEach((r) => {
    const c = countryOfRecord(r);
    if (!map.has(c.code)) map.set(c.code, { ...c, records: [] });
    map.get(c.code).records.push(r);
  });
  const groups = Array.from(map.values());
  groups.sort((a, b) => b.records.length - a.records.length || a.name.localeCompare(b.name));
  return groups;
}

function isValidContactRecord(rec) {
  if (!rec || rec.from === 'them') return false;
  const num = String(rec?.formatted || rec?.number || rec?.cleanNumber || '').trim();
  if (!num) return false;
  const digits = num.replace(/\D/g, '');
  return digits.length >= 7 && digits.length <= 15;
}

export function buildPdfModel(records, filterLabel, opts) {
  const filterKey = filterKeyFromLabel(filterLabel);
  const valid = (Array.isArray(records) ? records : []).filter(isValidContactRecord);
  // When records arrive pre-filtered (the caller already applied the status +
  // search filter), only drop non-contact records — never re-filter.
  const source = opts?.prefiltered ? valid : applyReportFilter(valid, filterKey);

  // Campaign-level totals always come from the FULL campaign dataset, never from
  // the filtered subset, so the KPI summary stays intact regardless of filter.
  const campaignRecords = (opts?.campaignRecords && Array.isArray(opts.campaignRecords))
    ? opts.campaignRecords.filter(isValidContactRecord)
    : valid;
  const totals = computeTotals(campaignRecords);
  const yieldRatio = totals.total > 0 ? Math.round((totals.registered / totals.total) * 100) : 0;
  const countries = buildCountryGroups(source);
  return { filterKey, records: source, totals, yieldRatio, countries, filteredCount: source.length };
}

